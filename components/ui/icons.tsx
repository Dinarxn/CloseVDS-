import React from "react";

/**
 * Standard Icon Sizes for CloseVDS Design System
 * - xs: 12px (inline status tags, micro badges)
 * - sm: 14px (compact table actions, meta indicators)
 * - md: 16px (default for buttons, nav items, form labels)
 * - lg: 20px (card headers, primary navigation headers)
 * - xl: 24px (hero sections, empty state illustrations)
 */
export const ICON_SIZES = {
  xs: 12,
  sm: 14,
  md: 16,
  lg: 20,
  xl: 24,
} as const;

export type IconNamedSize = keyof typeof ICON_SIZES;
export type IconSize = IconNamedSize | number | (string & {});

export function resolveIconSize(size?: IconSize): number | string {
  if (size === undefined) return ICON_SIZES.md;
  if (typeof size === "string" && size in ICON_SIZES) {
    return ICON_SIZES[size as IconNamedSize];
  }
  return size;
}

export interface IconProps extends Omit<React.SVGProps<SVGSVGElement>, "size"> {
  size?: IconSize;
  className?: string;
  strokeWidth?: number | string;
}

function baseIconProps(props: IconProps) {
  const { size = "md", className = "", strokeWidth = 1.75, ...rest } = props;
  const resolvedSize = resolveIconSize(size);

  return {
    xmlns: "http://www.w3.org/2000/svg",
    width: resolvedSize,
    height: resolvedSize,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": props["aria-label"] ? undefined : true,
    className: `shrink-0 ${className}`.trim(),
    ...rest,
  };
}

